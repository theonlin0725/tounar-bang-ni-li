// 只验证新入口的可操作性；隔离 outbox，不替代用户的 SMTP 收件箱自测。
import fs from 'node:fs';
import assert from 'node:assert/strict';
import { chromium, selectors } from 'playwright';
selectors.setTestIdAttribute('data-test');
import { startTestServer } from '../../server/test/helpers.js';
import { resolveChromiumExecutable } from './browser.mjs';
const server = await startTestServer({ name: 'mail-admin-web', env: { ALLOWED_EMAILS: 'admin@tounar.local,peer@tounar.local', ADMIN_EMAILS: 'admin@tounar.local', TEST_MAIL_RECIPIENTS: 'admin@tounar.local', ENABLE_MAIL_BUSINESS_TEST: 'true' } });
let browser;
try {
  const login = await server.login('admin@tounar.local');
  const executable = await resolveChromiumExecutable();
  browser = await chromium.launch({ executablePath: executable?.path, headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const [name, value] = login.cookie.split('=');
  await context.addCookies([{ name, value, url: server.base }]);
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => { errors.push(e.message); console.log('页面错误：'+e.stack); });
  page.setDefaultTimeout(10000);
  await page.goto(server.base+'/?panel=mail-admin');
  await page.getByRole('heading', { name: '邮件测试与模板', exact: true }).waitFor();
  await page.getByTestId('mail-preview-saved').click();
  await page.getByTestId('mail-preview').getByText('发送内容预览', { exact: true }).waitFor();
  await page.frameLocator('iframe.mail-preview-frame').getByText('你的帮你理登录验证码是：', { exact: true }).waitFor();
  assert.equal(await page.frameLocator('iframe.mail-preview-frame').locator('strong').evaluate(el => getComputedStyle(el).fontSize), '28px', '隔离预览应呈现实际邮件的内联排版');
  await page.getByTestId('mail-send').click();
  await page.getByTestId('mail-records').getByText(/模板试发 · 仅写本地文件/).waitFor();
  await page.locator('#mail-subject').fill('【Tounar 帮你理】登录验证码 文案B');
  await page.getByTestId('mail-save').click();
  await page.getByTestId('mail-active-version').filter({ hasText: '当前生效：v2' }).waitFor();
  await page.getByTestId('mail-preview-saved').click();
  await page.getByTestId('mail-send').click();
  await page.getByTestId('mail-records').getByText('【自测·模板试发】【Tounar 帮你理】登录验证码 文案B', { exact: true }).waitFor();
  assert.ok(server.latestOutbox('template_test').subject.includes('文案B'));
  await page.locator('#mail-history').selectOption('1');
  await page.getByRole('button', { name: '恢复所选版本并启用', exact: true }).click();
  await page.getByTestId('mail-active-version').filter({ hasText: '当前生效：v3' }).waitFor();
  await page.locator('#mail-var-code').fill('');
  await page.getByTestId('mail-preview-draft').click();
  await page.locator('.mail-error').filter({ hasText: '必填变量 code' }).waitFor();
  const app = await server.request('/api/v1/applications/manual', { method: 'POST', cookie: login.cookie, headers: { 'Idempotency-Key': crypto.randomUUID() }, body: { company_name: '自测科技', job_title: '产品经理', has_applied: true, status: 'applied', applied_at: new Date().toISOString(), jd_summary: '真实业务测试入口的隔离验证', job_url: 'https://example.com/jobs/self-test-web' } });
  assert.equal(app.status, 201);
  await page.reload();
  await page.getByTestId('mail-mode').selectOption('business');
  await page.getByTestId('mail-application').selectOption(app.json.data.id);
  await page.getByTestId('mail-preview-saved').click();
  await page.getByTestId('mail-preview').getByText(/自测科技·产品经理/).first().waitFor();
  await page.getByTestId('mail-send').click();
  await page.getByTestId('mail-records').getByText(/业务通路 · 仅写本地文件/).waitFor();
  assert.ok(server.latestOutbox('reminder').subject.startsWith('【自测·业务通路】'));
  fs.mkdirSync('.tmp/mail-admin-ui', { recursive: true });
  await page.screenshot({ path: '.tmp/mail-admin-ui/desktop.png', fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, '窄屏不应水平溢出');
  await page.screenshot({ path: '.tmp/mail-admin-ui/mobile.png', fullPage: true });
  await page.setViewportSize({ width: 812, height: 375 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  const peer = await server.login('peer@tounar.local');
  const other = await browser.newContext();
  const [peerName, peerValue] = peer.cookie.split('=');
  await other.addCookies([{ name: peerName, value: peerValue, url: server.base }]);
  const peerPage = await other.newPage(); await peerPage.goto(server.base+'/?panel=mail-admin');
  await peerPage.getByRole('alert').filter({ hasText: '仅管理员' }).waitFor();
  assert.deepEqual(errors, []);
  console.log('管理员页面验证通过：模板试发、修改生效、恢复、约束错误、业务通路、非管理员拦截、桌面和窄屏。全部 outbox，未发送真实邮件。');
} finally { if (browser) await browser.close(); await server.stop(); }
